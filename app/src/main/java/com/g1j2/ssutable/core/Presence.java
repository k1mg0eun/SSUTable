package com.g1j2.ssutable.core;

/** 학생회관 안/밖 판정. 위치 규칙은 이 값만 보고 정한다. */
public enum Presence {
    /** 학생회관 반경 안. */
    INSIDE,
    /** 학생회관 반경 밖. */
    OUTSIDE,
    /** 위치를 보고는 있지만 아직 판정이 없다 (첫 위치 전, 앱이 화면에 없을 때). 지금 상태를 유지한다. */
    UNKNOWN,
    /** 위치를 보지 않는다 (권한 없음 등). 도착은 어디서든, 반납은 시간으로만. */
    OFF
}
